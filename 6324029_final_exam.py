import os
import matplotlib.pyplot as plt
from collections import Counter

# パス
text_dir = '/content/drive/MyDrive/Colab Notebooks/dataset/text/'
text_path = os.path.join(text_dir, 'text_english.txt')

# フォルダが存在しない場合は自動作成
os.makedirs(text_dir, exist_ok=True)

if not os.path.exists(text_path):
    print(f"エラー: {text_path} にファイルが見つかりません。")
    print("Googleドライブの dataset フォルダの中に「text」フォルダを作り、そこに text_english.txt を入れてください。")
else:
    #ファイルの読み込み
    with open(text_path, 'r', encoding='utf-8') as f:
        text = f.read()

    # 小文字化し、記号をスペースに置換して単語に分割
    text_lower = text.lower()
    for symbol in [',', '.', '(', ')', ':', '"', '\n', '\r']:
        text_lower = text_lower.replace(symbol, ' ')
    words = text_lower.split()


    # 6-a. stop words 除去なしの 2-gram 作成
    bigrams_raw = [f"{words[i]} {words[i+1]}" for i in range(len(words)-1)]
    bigram_counts_raw = Counter(bigrams_raw)
    top10_raw = dict(bigram_counts_raw.most_common(10))


    # 6-b. stop words 除去ありの 2-gram 作成
    # stop words の定義
    stop_words = {'the', 'a', 'an', 'is', 'are', 'of', 'to', 'in', 'and', 'it', 'that', 'by', 'as', 'for', 'was', 'with', 'on'}

    # stop words を除外
    filtered_words = [w for w in words if w not in stop_words]

    # 2-gram を作成
    bigrams_filtered = [f"{filtered_words[i]} {filtered_words[i+1]}" for i in range(len(filtered_words)-1)]
    bigram_counts_filtered = Counter(bigrams_filtered)
    top10_filtered = dict(bigram_counts_filtered.most_common(10))


    # グラフの描画
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(12, 10))

    # 6-a の棒グラフ（除去なし）
    ax1.bar(top10_raw.keys(), top10_raw.values(), color='skyblue')
    ax1.set_title("6-a. Top 10 2-grams (Without Stop Words Removal)")
    ax1.set_ylabel("Frequency")
    ax1.tick_params(axis='x', rotation=15) # 文字が重ならないように少し斜めにする

    # 6-b の棒グラフ（除去あり）
    ax2.bar(top10_filtered.keys(), top10_filtered.values(), color='salmon')
    ax2.set_title("6-b. Top 10 2-grams (With Stop Words Removal)")
    ax2.set_ylabel("Frequency")
    ax2.tick_params(axis='x', rotation=15)

    plt.tight_layout() # グラフ同士の重なりを防ぐ
    plt.show()

"""###7. 動画の変わり目検出"""

import cv2
import numpy as np
import matplotlib.pyplot as plt
import os


# 課題７：動画の変わり目検出

# パスの設定
video_path = '/content/drive/MyDrive/Colab Notebooks/dataset/videos/Detection.mp4'
output_img_dir = '/content/drive/MyDrive/Colab Notebooks/dataset/images/output/'
# 画像出力用のフォルダがない場合は自動作成
os.makedirs(output_img_dir, exist_ok=True)

cap = cv2.VideoCapture(video_path)

if not cap.isOpened():
    print("動画を開けませんでした。dataset/videos/Detection.mp4 が正しくアップロードされているか確認しなさいなぁ。")
else:
    diff_values = []
    prev_gray = None
    frame_count = 0

    print("動画を全フレーム解析中")

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        # グレースケール化
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

        if prev_gray is not None:
            # t番目とt-1番目のフレームの各画素の差の絶対値を計算
            diff = np.abs(gray.astype(np.int16) - prev_gray.astype(np.int16))

            # 全画素の差を足し合わせる（変化量）
            total_diff = np.sum(diff)
            diff_values.append(total_diff)

        prev_gray = gray
        frame_count += 1

    cap.release()
    print("解析が完了しました。")


    # 7-a. 横軸が時間（フレーム）、縦軸が変化量のグラフを描画
    diff_values = np.array(diff_values)
    frames_range = range(1, len(diff_values) + 1)

    plt.figure(figsize=(12, 5))
    plt.plot(frames_range, diff_values, color='purple', label='Frame Difference')
    plt.title('7-a. Frame Difference Over Time (Detection.mp4)')
    plt.xlabel('Frame (t)')
    plt.ylabel('Total Pixel Difference')
    plt.grid(True)
    plt.show()


    # 7-b. 閾値の決め方を2種類試してフレームを出力

    # ①: 固定値による判定
    # 変化量の最大値の60%の値を閾値にする
    threshold_fixed = np.max(diff_values) * 0.6
    detected_fixed = np.where(diff_values > threshold_fixed)[0] + 1

    # ②: 統計値（平均 + 標準偏差の倍数）による自動判定
    # 全体の平均値に、標準偏差(std)の5倍を足した値を閾値とする
    mean_diff = np.mean(diff_values)
    std_diff = np.std(diff_values)
    threshold_stat = mean_diff + 5 * std_diff
    detected_stat = np.where(diff_values > threshold_stat)[0] + 1

    print("\n==========================================")
    print(" 7-b. 動画の変わり目 検出結果")
    print("==========================================")
    print(f"【方法1: 固定値（閾値: {threshold_fixed:.1f}）】")
    print(f"閾値を超えたフレーム番号:\n {list(detected_fixed)}")

    print(f"\n【方法2: 平均 + 5×標準偏差（閾値: {threshold_stat:.1f}）】")
    print(f"閾値を超えたフレーム番号:\n {list(detected_stat)}")


    # 確認用：変わり目のフレーム画像を保存する処理
    # 連続して閾値を超えた箇所を1つの変わり目としてまとめる
    unique_keyframes = []
    if len(detected_stat) > 0:
        unique_keyframes.append(detected_stat[0])
        for f in detected_stat:
            if f - unique_keyframes[-1] > 10: # 10フレーム以上離れていたら別のシーン
                unique_keyframes.append(f)

    print(f"\n【本当に変わり目か確認用の画像保存】")
    cap = cv2.VideoCapture(video_path)
    for f_num in unique_keyframes:
        cap.set(cv2.CAP_PROP_POS_FRAMES, f_num)
        ret, frame = cap.read()
        if ret:
            img_path = os.path.join(output_img_dir, f'scene_change_{f_num}.jpg')
            cv2.imwrite(img_path, frame)
            print(f"フレーム {f_num} の画像を保存しました -> {img_path}")
    cap.release()

"""###8. オブジェクト指向:Videoの作成"""

import cv2
import os


# 課題８：オブジェクト指向：Video クラスの作成


class Video:
    def __init__(self, path):
        """コンストラクタ：インスタンス変数の初期化"""
        self.path = path
        self.title = None
        self.video_id = None
        self.thumbnail = None

    def parse_filename(self):
        """クラスメソッド1：ファイル名からタイトルとIDを抽出（課題3）"""
        basename = os.path.basename(self.path)  # パスからファイル名本体を取得
        name_without_ext, _ = os.path.splitext(basename)
        parts = name_without_ext.split(" - ")

        self.title = parts[0]
        self.video_id = parts[1]

    def create_thumbnail(self):
        """クラスメソッド2：中央フレームからサムネイルを作成して代入（課題2）"""
        cap = cv2.VideoCapture(self.path)
        if cap.isOpened():
            total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            middle_frame_idx = total_frames // 2
            cap.set(cv2.CAP_PROP_POS_FRAMES, middle_frame_idx)
            ret, frame = cap.read()
            if ret:
                self.thumbnail = frame  # インスタンス変数に画像オブジェクトを代入
            cap.release()

    def get_info(self):
        """クラスメソッド3：4つの変数の値を辞書型で返す"""
        return {
            "path": self.path,
            "title": self.title,
            "video_id": self.video_id,
            "thumbnail": self.thumbnail
        }

    # 高階関数に渡すためのフレーム処理用関数群
    @staticmethod
    def reverse_filter(frame):
        """クラスメソッド4：色反転（課題4）"""
        return 255 - frame

    @staticmethod
    def gray_filter(frame):
        """クラスメソッド5：グレースケール化（3チャンネル形式で返す）"""
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        return cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)

    @staticmethod
    def binary_filter(frame):
        """クラスメソッド6：二値化（3チャンネル形式で返す）"""
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        _, binary = cv2.threshold(gray, 127, 255, cv2.THRESH_BINARY)
        return cv2.cvtColor(binary, cv2.COLOR_GRAY2BGR)

    def process_video(self, output_path, filter_func):
        """クラスメソッド7：高階関数。引数で受け取ったフィルター関数を全フレームに適用して動画を生成"""
        cap = cv2.VideoCapture(self.path)
        if not cap.isOpened():
            print("動画を開けませんでした。")
            return

        # 元動画の情報取得と0.3倍のサイズ計算
        width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        fps = cap.get(cv2.CAP_PROP_FPS)
        new_width = int(width * 0.3)
        new_height = int(height * 0.3)

        # 出力先フォルダの自動作成
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        fourcc = cv2.VideoWriter_fourcc(*'mp4v')
        out = cv2.VideoWriter(output_path, fourcc, fps, (new_width, new_height))

        while True:
            ret, frame = cap.read()
            if not ret:
                break

            # 引数として受け取った関数を適用
            processed_frame = filter_func(frame)

            # 0.3倍に縮小
            resized_frame = cv2.resize(processed_frame, (new_width, new_height))
            out.write(resized_frame)

        cap.release()
        out.release()
        print(f"動画処理が完了しました。保存先: {output_path}")



